#!/usr/bin/env python3
"""Emit cad/amip_params.scad from the canonical store.

🔑 THE DRAWING MUST NOT BE ABLE TO DRIFT FROM THE DESIGN. Every dimension here
is read through values.get() or derived by physics.design_point(), exactly as
the mesher reads them, so a change to baselines.json changes the drawing on the
next run and a stale drawing is a diff, not a surprise.

⚠️ This file is GENERATED. Edit scadgen.py or baselines.json, never the .scad.

    python3 cad/scadgen.py && openscad cad/view_barrel.scad
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import physics as ph                                            # noqa: E402
import values                                                   # noqa: E402


def main():
    a, L = ph.design_point(values.get("cavity.d_over_l"),
                           values.get("source.f0.ghz"))
    gw, gd = values.get("cavity.groove.mm")
    ld, lw = values.get("loop.size.mm")
    rows = [
        ("// ── cavity ──", None, None),
        ("cav_r", a, "mm  cavity radius (H1: D/L = %.3f)"
                     % values.get("cavity.d_over_l")),
        ("cav_l", L, "mm  cavity length; z spans -cav_l/2 .. +cav_l/2"),
        ("f0_ghz", values.get("source.f0.ghz"), "GHz  design frequency"),
        ("// ── mode filter: corner groove, BOTH end caps ──", None, None),
        ("groove_w", gw, "mm  radial width, measured inward from cav_r"),
        ("groove_d", gd, "mm  axial depth, OUTWARD past the end cap"),
        ("// ── coupling loop ──", None, None),
        ("loop_d", ld, "mm  depth the loop reaches into the cavity"),
        ("loop_hw", lw, "mm  HALF-width; area = loop_d * 2 * loop_hw"),
        ("loop_rw", values.get("loop.wire_r.mm", allow_tentative=True),
         "mm  wire radius  ⚠️ TENTATIVE: never chosen"),
        ("loop_gap", values.get("loop.gap.mm", allow_tentative=True),
         "mm  PORT gap at the crossbar  ⚠️ TENTATIVE"),
        ("loop_phi", values.get("loop.phi.deg"), "deg  azimuth (sector centre)"),
        ("cap_r_frac", values.get("loop.cap_r_frac"),
         "1   cap-mount radius as a fraction of cav_r"),
        ("// ── series capacitor (barrel mount only) ──", None, None),
        ("gap2", 0.5, "mm  conductor break in the -y leg  [step-2 sweep]"),
        ("flange_r", 1.9, "mm  disc radius; 0.196 pF cancels 332 ohm  [swept]"),
        ("flange_t", 0.3, "mm  disc thickness (geometry.py default)"),
    ]
    out = ["// GENERATED by cad/scadgen.py — DO NOT EDIT.",
           "// Source: baselines.json + physics.design_point().",
           "// Regenerate:  python3 cad/scadgen.py", ""]
    for name, val, note in rows:
        if val is None:
            out += ["", name]
            continue
        out.append(f"{name} = {val:.6g};" + (f"   // {note}" if note else ""))
    out += ["", "// derived, so the views cannot disagree with each other",
            "loop_area = loop_d * 2 * loop_hw;   // mm^2",
            "cap_r     = cav_r * cap_r_frac;     // cap-mount radius",
            "barrel_xo = cav_r + 2;              // leg start, OUTSIDE the wall",
            "barrel_xi = cav_r - loop_d;         // leg end, inside",
            ""]
    p = pathlib.Path(__file__).with_name("amip_params.scad")
    p.write_text("\n".join(out) + "\n")
    print(f"  ✅ {p.name}: cav_r={a:.4f} cav_l={L:.4f} groove={gw:g}x{gd:g} "
          f"loop={ld:g}x{lw:g} ({ld*2*lw:.0f} mm^2)")


if __name__ == "__main__":
    main()
